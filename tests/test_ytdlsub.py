import pytest
import yaml

from nrk_star_to_ytdlsub import nrk, ytdlsub


def _fav(title: str, url: str, content_id: str = "id") -> nrk.Favourite:
    return nrk.Favourite(
        content_type="series",
        content_id=content_id,
        title=title,
        url=url,
        medium="tv",
    )


def test_build_basic_document():
    doc = ytdlsub.build_subscription_data(
        [_fav("Kongen av Gulset", "https://tv.nrk.no/serie/kongen-av-gulset")]
    )

    # Minimal by default: just the preset group + genre + entries.
    assert set(doc) == {"__preset__", "NRK TV Show"}
    assert doc["__preset__"] == {"output_options": {"maintain_download_archive": True}}
    assert doc["NRK TV Show"]["= NRK"] == {
        "Kongen av Gulset": "https://tv.nrk.no/serie/kongen-av-gulset"
    }


def test_tv_show_directory_and_only_recent_are_optional_overrides():
    doc = ytdlsub.build_subscription_data(
        [_fav("Show", "https://tv.nrk.no/serie/show")],
        tv_show_directory="/tv_shows",
        only_recent_days=30,
    )
    overrides = doc["__preset__"]["overrides"]
    assert overrides["tv_show_directory"] == "/tv_shows"
    assert overrides["only_recent_date_range"] == "30days"


def test_custom_preset_used_as_group_key():
    doc = ytdlsub.build_subscription_data(
        [_fav("Show", "https://tv.nrk.no/serie/show")], preset="Emby TV Show"
    )
    assert "Emby TV Show" in doc
    assert "NRK TV Show" not in doc


def test_duplicate_titles_are_disambiguated():
    doc = ytdlsub.build_subscription_data(
        [
            _fav("Bancroft", "https://tv.nrk.no/serie/bancroft", "bancroft"),
            _fav("Bancroft", "https://tv.nrk.no/serie/bancroft-2", "bancroft-2"),
        ]
    )
    shows = doc["NRK TV Show"]["= NRK"]
    assert set(shows) == {"Bancroft", "Bancroft (bancroft-2)"}


def test_genre_can_be_disabled():
    doc = ytdlsub.build_subscription_data(
        [_fav("Show", "https://tv.nrk.no/serie/show")], genre=None
    )
    assert "Show" in doc["NRK TV Show"]


def test_empty_favourites_raises():
    with pytest.raises(ValueError):
        ytdlsub.build_subscription_data([])


def test_dump_is_valid_yaml_and_has_header():
    doc = ytdlsub.build_subscription_data([_fav("Show", "https://tv.nrk.no/serie/show")])
    text = ytdlsub.dump_subscriptions(doc)
    assert text.startswith("# Generated by nrk-star-to-ytdlsub")
    assert yaml.safe_load(text) == doc
