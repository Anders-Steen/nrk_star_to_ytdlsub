"""Turn NRK favourites into a ytdl-sub subscriptions file.

The generated file is deliberately minimal: it references a preset by name and
lists ``"<title>": "<url>"`` entries. All the player-specific configuration
(Jellyfin/Emby/Plex, quality, filters, subtitles, ...) lives in that preset in
your ``config.yaml``, so the same generator works for any player - just point
``--preset`` at the matching preset.
"""

from __future__ import annotations

from collections import OrderedDict
from typing import Iterable

import yaml

from .nrk import Favourite

DEFAULT_PRESET = "NRK TV Show"
DEFAULT_TV_SHOW_DIRECTORY = "/tv_shows"


def _subscription_name(fav: Favourite, used: set[str]) -> str:
    name = fav.title.strip() or fav.content_id
    if name not in used:
        used.add(name)
        return name
    candidate = f"{name} ({fav.content_id})"
    used.add(candidate)
    return candidate


def build_subscription_data(
    favourites: Iterable[Favourite],
    *,
    preset: str = DEFAULT_PRESET,
    tv_show_directory: str | None = None,
    genre: str | None = "NRK",
    only_recent_days: int | None = None,
    maintain_download_archive: bool = True,
) -> dict:
    """Return a ytdl-sub subscriptions document as a plain dict.

    ``tv_show_directory`` and ``only_recent_days`` are written into the file's
    ``__preset__`` overrides only when set. Note that ytdl-sub gives
    ``__preset__`` overrides higher precedence than preset-level overrides, so
    setting them here intentionally wins over the referenced preset.
    """
    used: set[str] = set()
    entries: "OrderedDict[str, str]" = OrderedDict()
    for fav in favourites:
        name = _subscription_name(fav, used)
        entries[name] = fav.url

    if not entries:
        raise ValueError("no favourites to write")

    file_overrides: dict[str, object] = {}
    if tv_show_directory:
        file_overrides["tv_show_directory"] = tv_show_directory
    if only_recent_days is not None:
        file_overrides["only_recent_date_range"] = f"{int(only_recent_days)}days"

    document: dict = {}
    file_preset: dict = {}
    if file_overrides:
        file_preset["overrides"] = file_overrides
    if maintain_download_archive:
        file_preset["output_options"] = {"maintain_download_archive": True}
    if file_preset:
        document["__preset__"] = file_preset

    body: dict = dict(entries)
    if genre:
        body = {f"= {genre}": body}
    document[preset] = body
    return document


def dump_subscriptions(document: dict) -> str:
    header = (
        "# Generated by nrk-star-to-ytdlsub. Do not edit by hand:\n"
        "# run `nrk-star-to-ytdlsub sync` to regenerate it.\n"
    )
    return header + yaml.safe_dump(
        document,
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
    )
